import type { HistoricalOutcome } from "../types.js";

// Historical episode library for the analogue engine.
// Outcome figures are approximate, widely documented market moves (rounded);
// they are presented in the UI as "approximate historical statistics", with
// this file as the methodology reference. Sources: public market history
// (S&P/Dow archives, FRED, EIA oil price history, LBMA gold history).

export interface HistoricalEpisode {
  id: string;
  name: string;
  year: number;
  start: string; // ISO date of shock onset
  tags: string[]; // matched against category analogueTags
  magnitude: number; // 1-3 subjective shock size
  summary: string;
  context: string;
  outcomes: HistoricalOutcome[];
}

const O = (asset: string, horizon: string, movePct: number, note?: string): HistoricalOutcome => ({
  asset,
  horizon,
  movePct,
  note,
});

